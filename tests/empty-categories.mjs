import assert from 'node:assert/strict';
import * as standings from '../public/standings.js';
import fs from 'node:fs';
import vm from 'node:vm';
import {parseCsv,buildCompetition,withAddedBouts,addEmptyCategories,addCategoryPlayer,projectCompetition,buildAwardState} from '../server.mjs';
const comp=buildCompetition(parseCsv(fs.readFileSync(new URL('../csv/perlis_day_1.csv',import.meta.url),'utf8')));
const state={version:20,bouts:{[comp.bouts[0].id]:{winnerId:'existing-winner'}},awards:{existing:{medalists:{old:{state:'DELIVERED'}}}},poomsae:{E001:{rank:1}},schedule:{'1:A':['keep-this-order']},audit:[]};
const before=JSON.stringify({bouts:state.bouts,awards:state.awards,poomsae:state.poomsae,schedule:state.schedule});
const names=['A Friendly A1','A Friendly A2','A Friendly A3'];
const added=addEmptyCategories(state,comp,{ring:'A',names});
assert.equal(added.created.length,3);
assert.equal(new Set(added.created.map(b=>b.id)).size,3);
assert(added.created.every(b=>b.manual&&b.stage===0&&!b.directIds.length));
assert.equal(JSON.stringify({bouts:state.bouts,awards:state.awards,poomsae:state.poomsae,schedule:state.schedule}),before);
const active=()=>withAddedBouts(comp,state);
assert.equal(addEmptyCategories(state,active(),{ring:'A',names}).created.length,0);
assert.equal(addEmptyCategories(state,active(),{ring:'A',names:['a friendly a1']}).existing.length,1);
assert.throws(()=>addEmptyCategories(state,active(),{ring:'H',names}),/ring/);
assert.throws(()=>addEmptyCategories(state,active(),{ring:'A',names:['Valid','']}),/1–120/);
assert.equal(state.manualBouts.length,3);
const boutId=added.created[0].id;
const project=()=>projectCompetition(active(),state).find(b=>b.id===boutId);
assert.equal(project().status,'WAITING');assert.equal(project().winnerId,null);
assert.equal(buildAwardState(projectCompetition(active(),state)).find(a=>a.category===names[0]).finished,false);
const blue=addCategoryPlayer(state,active(),{boutId,corner:'B',name:'Blue athlete',team:'School A'});
assert.equal(project().status,'WAITING');assert.equal(project().winnerId,null); // No automatic one-player gold.
assert.throws(()=>addCategoryPlayer(state,active(),{boutId,corner:'B',name:'Overwrite',team:'School B'}),/occupied/);
assert.throws(()=>addCategoryPlayer(state,active(),{boutId,corner:'R',name:'Blue athlete',team:'School A'}),/already/);
assert.throws(()=>addCategoryPlayer(state,active(),{boutId,corner:'R',name:'',team:'School B'}),/name/);
const red=addCategoryPlayer(state,active(),{boutId,corner:'R',name:'Red athlete',team:'School B'});
assert.equal(project().status,'READY');assert.equal(project().blueId,blue.id);assert.equal(project().redId,red.id);
assert.throws(()=>addCategoryPlayer(state,active(),{boutId,corner:'R',name:'Third',team:'School C'}),/occupied/);
state.bouts[boutId]={winnerId:blue.id,method:'POINTS'};
assert.equal(project().status,'COMPLETE');
const award=buildAwardState(projectCompetition(active(),state)).find(a=>a.category===names[0]);
assert(award.finished&&!award.autoRing);assert.deepEqual(award.medals.map(m=>m.athleteId),[blue.id,red.id]);
assert.throws(()=>addCategoryPlayer(state,active(),{boutId,corner:'B',name:'Changed',team:'School A'}),/result/);
// JSON storage/restart keeps new categories, players, and the entered result.
const restored=JSON.parse(JSON.stringify(state));
assert.equal(projectCompetition(withAddedBouts(comp,restored),restored).find(b=>b.id===boutId).status,'COMPLETE');
// Existing qualifier routing also works when its destination is a new category.
delete state.bouts[boutId];
state.extraAthletes.push({id:'challenger',day:1,event:'KYORUGI',name:'Third',team:'School C',category:names[0],route:[]});
state.extraBouts=[{id:'qualifier',code:'A060Z',targetBoutId:boutId,sourceId:blue.id,sourceType:'direct',challengerId:'challenger',sourceCorner:'B',challengerCorner:'R'}];
assert.equal(project().status,'WAITING');
state.bouts.qualifier={winnerId:'challenger',method:'POINTS'};
assert.equal(project().status,'READY');assert.equal(project().blueId,'challenger');
// Frontend shows empty categories and the player form, and retains typed drafts on render.
const source=fs.readFileSync(new URL('../public/app.js',import.meta.url),'utf8').replace(/^import .*\n/,'').replace(/refresh\(\);\s*setInterval\(\(\) => refresh\(true\), 10000\);\s*$/,'');
const fixture={event:{name:'PERLIS',shortName:'PERLIS',dates:['31 October 2026']},version:20,bouts:projectCompetition(active(),state),athletes:active().athletes,poomsae:[],awards:[]};
const context=vm.createContext({...standings,calculateStandings:standings.teamStandings,document:{querySelector:()=>({})},location:{pathname:'/admin/qualifying',search:''},URLSearchParams,sessionStorage:{getItem:()=>''},fixture});
vm.runInContext(source,context);vm.runInContext("data=fixture;role='admin';categoryCreateDraft.names='My next category';categoryPlayerDraft.name='Keep typed name';",context);
const html=vm.runInContext('adminQualifyingContent()',context);
assert(html.includes('Create with 0 players'));assert(html.includes('A Friendly A2'));assert(html.includes('0/2 slots filled'));
assert(html.includes('My next category'));assert(html.includes('Keep typed name'));assert(html.includes('category-player-form'));
vm.runInContext("ring='A';query='A Friendly A2';",context);
assert(vm.runInContext('schedule()',context).includes('A Friendly A2'));
assert(vm.runInContext('brackets()',context).includes('A Friendly A2'));
console.log('PASS: empty categories, idempotent creation, preserved tournament state, player validation, waiting/ready/results/awards, restart, qualifier routing, and public/admin views.');
